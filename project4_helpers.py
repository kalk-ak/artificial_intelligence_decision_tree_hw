def load_kernel_audio(install=True):
    """Import sounddevice and soundfile. If they are missing, pip-install them into this environment once, then import."""
    global sd, sf, HAVE_KERNEL_AUDIO, KERNEL_AUDIO_PROBLEM
    if HAVE_KERNEL_AUDIO:
        return True
    for attempt in ("import", "install"):
        try:
            import sounddevice as _sd
            import soundfile as _sf
            sd, sf = _sd, _sf
            HAVE_KERNEL_AUDIO, KERNEL_AUDIO_PROBLEM = True, ""
            return True
        except ModuleNotFoundError as exc:
            KERNEL_AUDIO_PROBLEM = f"{type(exc).__name__}: {exc}"
            if attempt == "install" or not install:
                return False
            print("Setting up the voice recorder: installing sounddevice and soundfile into this environment "
                  "(only the first time, about 30 seconds)...")
            result = subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", "sounddevice>=0.4.6", "soundfile>=0.12"],
                                    capture_output=True, text=True)
            if result.returncode != 0:
                KERNEL_AUDIO_PROBLEM = "pip could not install them: " + (result.stderr or result.stdout).strip()[-300:]
                return False
            importlib.invalidate_caches()
        except Exception as exc:                   # OSError: the PortAudio library is missing (Linux)
            KERNEL_AUDIO_PROBLEM = f"{type(exc).__name__}: {exc}"
            return False
    return False


