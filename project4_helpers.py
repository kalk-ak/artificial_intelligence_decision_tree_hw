def encode_audio(samples, samplerate):
    """Compress a mono float recording to Ogg Vorbis (small files), or to 16-bit WAV if Ogg is not available."""
    for fmt, subtype, mime in (("OGG", "VORBIS", "audio/ogg"), ("WAV", "PCM_16", "audio/wav")):
        buffer = io.BytesIO()
        try:
            with sf.SoundFile(buffer, mode="w", samplerate=samplerate, channels=1, format=fmt, subtype=subtype) as out:
                for start in range(0, len(samples), 32768):        # write in blocks; very large Vorbis writes can fail
                    out.write(samples[start:start + 32768])
            return buffer.getvalue(), mime
        except Exception:
            continue
    raise RuntimeError("soundfile could not encode the recording as Ogg or WAV")


